<h1>Privacy policy</h1>
<p>Missionnaire Studio and Missionnaire Admin · Last updated: September 12, 2026</p>
<p>
	This policy describes how Missionnaire Network handles information when you use Missionnaire
	Studio, its Admin connection, and its Google/YouTube integration. Contact: <a
		href="mailto:misssionnaireapp@gmail.com">misssionnaireapp@gmail.com</a
	>.
</p>
<h2>Information we access and store</h2>
<ul>
	<li>
		<strong>Admin and device information:</strong> your Admin email, name, permissions, Studio approval
		and expiry dates, device identifier, device name, operating system, local device username, and connection
		activity help us authorize and manage your Studio computer.
	</li>
	<li>
		<strong>Google and YouTube information:</strong> when you connect a channel, we access its identifier
		and title and store them with your Admin email and connection timestamps. We receive OAuth access
		and refresh tokens. Refresh tokens are encrypted before storage on the Admin server and let the server
		renew access without asking you to sign in for every broadcast. We do not receive your Google password.
	</li>
	<li>
		<strong>Broadcast information:</strong> we process channel, stream and broadcast identifiers, titles,
		descriptions, schedules, visibility settings, thumbnails, live status and stream connection details
		to operate the broadcasts you request.
	</li>
	<li>
		<strong>Production content:</strong> Studio processes the audio, video and media sources you select.
		Content is transmitted to your selected streaming destinations when you broadcast; cloud recording
		features store the recordings you create.
	</li>
	<li>
		<strong>Technical information:</strong> our website processes request information such as IP address,
		browser/device information, visited pages, referrer and approximate country and city for operation
		and visitor statistics. Session cookies and local storage support authentication, preferences and
		cached media. Embedded third-party content may use its own cookies or similar technologies.
	</li>
</ul>
<h2>How we use your information</h2>
<p>
	We use this information to verify Admin permissions, connect approved Studio devices, display
	connected channels, create and manage requested YouTube broadcasts, operate recordings,
	troubleshoot failures and protect the service. The Google permission requested is <code
		>youtube.force-ssl</code
	>; the app uses it for channel and live broadcast operations. It does not request access to Gmail,
	Google Drive or Google contacts.
</p>
<h2>Sharing and third parties</h2>
<p>
	Google/YouTube receives authorization requests, broadcast details and media needed to provide the
	YouTube features. Our hosting, database and media storage providers process information needed to
	operate the service. Authorized Missionnaire administrators can access information needed for
	administration and support. Broadcasts and published recordings are accessible according to the
	destination and visibility settings you choose. Information may also be disclosed where required
	by law.
</p>
<p>
	We do not sell Google user data or use it for advertising, profiling or training generalized AI
	models. Missionnaire Studio's use and transfer of information received from Google APIs will
	adhere to the <a href="https://developers.google.com/terms/api-services-user-data-policy"
		>Google API Services User Data Policy</a
	>, including the Limited Use requirements.
</p>
<p>
	Missionnaire Studio uses YouTube API Services. Google's processing is described in the <a
		href="https://policies.google.com/privacy">Google Privacy Policy</a
	>. Embedded YouTube content is provided by YouTube and may include advertisements.
</p>
<h2>Storage and protection</h2>
<p>
	Admin stores account connections and operational records on its servers and database. Studio also
	keeps local settings and selected media on your computer. Server-side refresh tokens are
	encrypted; Admin permission checks limit access to Studio operations. Protect your Admin account
	and any computer approved to use Studio.
</p>
<h2>Retention, disconnection and deletion</h2>
<p>
	The YouTube connection record remains stored until you disconnect that channel. Disconnecting it
	in Studio deletes its stored channel authorization and refresh token from the active database. It
	does not delete videos already published on YouTube or separately stored recordings.
</p>
<p>
	To revoke Google's authorization, remove Missionnaire Studio (or the previous consent-screen name,
	“Admin Studio app”) from <a href="https://security.google.com/settings/security/permissions"
		>your Google account permissions</a
	>. Revocation prevents further authorized Google access; it does not by itself remove all
	Missionnaire records. Use Studio's disconnect action as well to remove the stored connection.
</p>
<p>
	For deletion of your remaining account, device, recording or associated personal data, email <a
		href="mailto:misssionnaireapp@gmail.com">misssionnaireapp@gmail.com</a
	> from your Admin account email and identify the account or channel and the data you want deleted. We
	may verify ownership before processing the request. Do not send passwords, tokens or stream keys. Any
	records that must be retained for a legal obligation will be explained when handling your request.
</p>
<h2>Your choices and policy updates</h2>
<p>
	You can decline Google authorization, disconnect channels, revoke Google access, and contact us to
	request access, correction or deletion of your information. YouTube features require a connected
	channel. We publish policy changes on this page and update the date above.
</p>
