<h1>Missionnaire Studio</h1>
<p>
	Missionnaire Studio is the live production application from Missionnaire Network. It helps
	authorized operators prepare live sessions, combine audio and video sources, manage recordings,
	and broadcast to connected YouTube channels through Missionnaire Admin.
</p>
<h2>Your Admin account, connected to Studio</h2>
<ol>
	<li>Open Missionnaire Studio and choose the Admin connection.</li>
	<li>
		Sign in to your Missionnaire Admin account in your browser. An account with recording management
		permission must approve the Studio computer.
	</li>
	<li>
		From Studio, choose to add a YouTube channel. Google asks you to choose an account and authorize
		YouTube access.
	</li>
	<li>
		Return to Studio to select a connected channel, prepare your broadcast, and control when it goes
		live.
	</li>
</ol>
<p>
	Admin determines which users may operate Studio. Connecting a Google account authorizes YouTube
	features; it does not create an Admin account or grant additional Admin permissions. Studio
	computer approvals last 30 days unless revoked earlier.
</p>
<h2>Why we request Google access</h2>
<p>
	Missionnaire Studio uses YouTube API Services to identify your channel, create and manage live
	streams and broadcasts, set broadcast details and thumbnails, and start or end broadcasts you
	control. These operations require the YouTube permission shown on Google's consent screen. You may
	disconnect a channel in Studio and revoke Google access at any time.
</p>
